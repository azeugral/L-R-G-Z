  var STORAGE_KEY = 'lrgz_lang';
  var lang = 'pt';
  var observer = null;
  var lastDispatched = null;

  function translate(raw){
    var key = raw.trim();
    if(!key) return null;
    if(Object.prototype.hasOwnProperty.call(EN, key)) return EN[key];
    return null;
  }
  function swap(raw, t){
    return raw.match(/^\s*/)[0] + t + raw.match(/\s*$/)[0];
  }

  var SKIP_TAGS = { SCRIPT:1, STYLE:1, NOSCRIPT:1, SVG:1 };
  /* o hero e o terminal são gerados por JS e traduzidos na fonte, não pelo walker */
  var SKIP_IDS  = { heroTitle:1, terminalBody:1 };
  var ATTRS = ['placeholder','aria-label','alt','title','content'];

  function walkText(root){
    var tw = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function(node){
        var p = node.parentNode;
        while(p && p.nodeType === 1){
          if(SKIP_TAGS[p.tagName] || SKIP_IDS[p.id]) return NodeFilter.FILTER_REJECT;
          p = p.parentNode;
        }
        return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    var nodes = [], n;
    while((n = tw.nextNode())) nodes.push(n);
    nodes.forEach(function(node){
      if(node.__pt === undefined) node.__pt = node.nodeValue;
      if(lang === 'pt'){ node.nodeValue = node.__pt; return; }
      var t = translate(node.__pt);
      if(t !== null) node.nodeValue = swap(node.__pt, t);
    });
  }

  function walkAttrs(root){
    var els = Array.prototype.slice.call(root.querySelectorAll('*'));
    els.forEach(function(el){
      ATTRS.forEach(function(a){
        if(!el.hasAttribute(a)) return;
        if(a === 'content' && el.getAttribute('name') !== 'description') return;
        var k = '__pt_' + a;
        if(el[k] === undefined) el[k] = el.getAttribute(a);
        if(lang === 'pt'){ el.setAttribute(a, el[k]); return; }
        var t = translate(el[k]);
        if(t !== null) el.setAttribute(a, t);
      });
    });
  }

  function apply(){
    if(observer) observer.disconnect();

    walkText(document.body);
    walkAttrs(document.body);
    walkAttrs(document.head);

    if(document.__ptTitle === undefined) document.__ptTitle = document.title;
    document.title = lang === 'pt' ? document.__ptTitle : (translate(document.__ptTitle) || document.__ptTitle);
    document.documentElement.setAttribute('lang', lang === 'pt' ? 'pt-BR' : 'en-US');

    /* elementos marcados para aparecer só num idioma:
       data-only="pt" ou data-only="en" */
    Array.prototype.forEach.call(document.querySelectorAll('[data-only]'), function(el){
      el.style.display = (el.getAttribute('data-only') === lang) ? '' : 'none';
    });

    Array.prototype.forEach.call(document.querySelectorAll('.lang-toggle'), function(btn){
      btn.setAttribute('data-lang', lang);
      btn.setAttribute('aria-label', lang === 'pt' ? 'Switch to English' : 'Mudar para português');
      var pt = btn.querySelector('[data-l-pt]'), en = btn.querySelector('[data-l-en]');
      if(pt) pt.classList.toggle('on', lang === 'pt');
      if(en) en.classList.toggle('on', lang === 'en');
    });

    window.LRGZ_LANG = lang;
    /* só avisa quando o idioma REALMENTE muda — senão o terminal, que muda o
       DOM a cada caractere, dispararia o observer e reiniciaria a si mesmo em loop */
    if(lastDispatched !== lang){
      lastDispatched = lang;
      document.dispatchEvent(new CustomEvent('lrgz:lang', { detail:{ lang: lang } }));
    }

    if(observer) observer.observe(document.body, { childList:true, subtree:true });
  }

  function setLang(next){
    lang = (next === 'en') ? 'en' : 'pt';
    try { localStorage.setItem(STORAGE_KEY, lang); } catch(e){}
    apply();
  }

  try {
    var saved = localStorage.getItem(STORAGE_KEY);
    if(saved === 'en' || saved === 'pt') lang = saved;
    /* sem deteccao automatica pelo idioma do navegador: o robo do Google
       navega em ingles e indexava a versao EN. Ingles so pelo botao. */
  } catch(e){}

  window.LRGZ_LANG = lang;
  window.LRGZ_JS_LINES = (typeof JS_LINES !== 'undefined') ? JS_LINES : null;

  function boot(){
    observer = new MutationObserver(function(muts){
      if(lang === 'pt') return;
      /* ignora mutações dentro do hero e do terminal: esses são animados e
         já traduzidos na fonte, então não precisam (nem devem) ser revarridos */
      var relevant = muts.some(function(m){
        var n = m.target;
        while(n && n.nodeType === 1){
          if(SKIP_IDS[n.id]) return false;
          n = n.parentNode;
        }
        return true;
      });
      if(!relevant) return;
      clearTimeout(observer.__t);
      observer.__t = setTimeout(apply, 20);
    });
    apply();
    document.addEventListener('click', function(e){
      var b = e.target.closest && e.target.closest('.lang-toggle');
      if(!b) return;
      e.preventDefault();
      setLang(lang === 'pt' ? 'en' : 'pt');
    });
  }
  if(document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
  else boot();

  window.LRGZ_I18N = { setLang:setLang, apply:apply, get lang(){ return lang; } };

